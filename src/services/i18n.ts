export function getLocalizedSlide(slide: SlideData, lang: Language): LocalizedSlideContent {
  if (slide.translations && slide.translations[lang]) {
    return slide.translations[lang];
  }

  // Fallback generation based on current fields
  const narration = (lang === 'pt' && slide.narration.pt)
    ? slide.narration.pt
    : (lang === 'en' ? slide.narration.en : slide.narration.es);

  return {
    badge: slide.badge,
    title: slide.title,
    subtitle: slide.subtitle,
    takeaway: slide.takeaway || '',
    bullets: slide.bullets || [],
    metrics: slide.metrics || [],
    narration: narration
  };
}
